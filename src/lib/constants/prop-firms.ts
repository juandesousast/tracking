/**
 * Find known prop firm matching firmName by exact name, aliases, or fuzzy match.
 */
export function findKnownPropFirm(firmName: string): KnownPropFirm | undefined {
  if (!firmName || !firmName.trim()) return undefined;
  const normalized = firmName.trim().toLowerCase();

  // 1. Exact match by name (case-insensitive)
  const exact = KNOWN_PROP_FIRMS.find((f) => f.name.toLowerCase() === normalized);
  if (exact) return exact;

  // 2. Exact match by aliases (case-insensitive)
  const aliasMatch = KNOWN_PROP_FIRMS.find((f) =>
    f.aliases.some((a) => a.toLowerCase() === normalized)
  );
  if (aliasMatch) return aliasMatch;

  // 3. Partial/contains match
  return KNOWN_PROP_FIRMS.find((f) => {
    const fLower = f.name.toLowerCase();
    if (normalized.includes(fLower) || fLower.includes(normalized)) return true;
    return f.aliases.some(
      (a) => normalized.includes(a.toLowerCase()) || a.toLowerCase().includes(normalized)
    );
  });
}

/**
 * Returns customLogoUrl if provided (migrating any legacy Clearbit URLs to Google FaviconV2),
 * otherwise looks up the known prop firm catalog tolerantly by firmName,
 * or derives the favicon from the firm's website domain.
 */
export function getPropFirmLogo(
  firmName: string,
  customLogoUrl?: string | null,
  website?: string | null
): string | null {
  if (customLogoUrl && customLogoUrl.trim() !== '') {
    const trimmed = customLogoUrl.trim();
    // Upgrade legacy broken clearbit URLs to Google FaviconV2 CDN
    if (trimmed.includes('logo.clearbit.com/')) {
      const domain = trimmed.replace(/^.*logo\.clearbit\.com\//, '').replace(/\/$/, '');
      return `https://t2.gstatic.com/faviconV2?client=SOCIAL&type=FAVICON&fallback_opts=TYPE,SIZE,URL&url=https://${domain}&size=128`;
    }
    return trimmed;
  }

  const match = findKnownPropFirm(firmName);
  if (match) return match.logoUrl;

  if (website && website.trim() !== '') {
    const cleanDomain = website.trim().replace(/^https?:\/\//, '').replace(/\/.*$/, '');
    if (cleanDomain) {
      return `https://t2.gstatic.com/faviconV2?client=SOCIAL&type=FAVICON&fallback_opts=TYPE,SIZE,URL&url=https://${cleanDomain}&size=128`;
    }
  }

  return null;
}
